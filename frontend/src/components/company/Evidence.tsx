"use client";

import { createContext, useContext, useState } from "react";
import type { Json } from "@/lib/api";
import { byUnit, fy, inr } from "@/lib/format";
import { Modal } from "../ui";

// Any statement or metric in the dashboard can open this drawer to show the numbers behind it.
export type EvidenceItem = {
  title: string;
  plain?: string;
  detail?: string;
  formula?: string;
  unit?: string;
  points?: Json[];   // [{period, value, inputs, note}]
  inputs?: Json[];   // flat list of input facts
};

const Ctx = createContext<(e: EvidenceItem) => void>(() => {});
export const useEvidence = () => useContext(Ctx);

export function EvidenceProvider({ children }: { children: React.ReactNode }) {
  const [item, setItem] = useState<EvidenceItem | null>(null);
  return (
    <Ctx.Provider value={setItem}>
      {children}
      <Modal open={!!item} onClose={() => setItem(null)} title={item?.title ?? ""}>
        {item && <EvidenceBody item={item} />}
      </Modal>
    </Ctx.Provider>
  );
}

function fmtInput(i: Json): string {
  if (i.value === null || i.value === undefined) return "not reported";
  const u = i.unit ?? "";
  if (u.endsWith("/share")) return `₹${Number(i.value).toFixed(2)}`;
  if (u === "shares") return byUnit(i.value, "shares");
  if (i.metric === "market_cap" || u === "INR" || (typeof i.value === "number" && Math.abs(i.value) > 1e6)) return inr(i.value);
  return typeof i.value === "number" ? i.value.toLocaleString("en-IN", { maximumFractionDigits: 4 }) : String(i.value);
}

function InputsTable({ inputs }: { inputs: Json[] }) {
  if (!inputs?.length) return null;
  return (
    <table className="w-full text-[12px]">
      <thead>
        <tr className="text-left text-ink-400">
          <th className="py-1 font-normal">Input</th>
          <th className="py-1 font-normal">Period</th>
          <th className="py-1 text-right font-normal">Value</th>
          <th className="py-1 pl-3 font-normal">Source</th>
        </tr>
      </thead>
      <tbody className="num">
        {inputs.map((i, k) => (
          <tr key={k} className="border-t border-ink-800">
            <td className="py-1 font-sans text-ink-200">{i.source_label ?? i.metric ?? i.symbol ?? "—"}</td>
            <td className="py-1 text-ink-300">{i.period ? `${fy(i.period)}${i.period_type === "quarterly" ? " (Q)" : ""}` : i.as_of?.slice(0, 10) ?? "—"}</td>
            <td className="py-1 text-right text-ink-100">{fmtInput(i)}</td>
            <td className="py-1 pl-3 font-sans text-ink-400">{i.source ?? "derived"}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

function EvidenceBody({ item }: { item: EvidenceItem }) {
  return (
    <div className="space-y-4 text-[13px]">
      {item.plain && <p className="text-ink-200">{item.plain}</p>}
      {item.detail && <p className="rounded-md bg-ink-850 p-3 text-ink-300">{item.detail}</p>}
      {item.formula && (
        <p className="text-ink-400">
          <span className="label mr-2">Formula</span>
          <span className="num text-ink-200">{item.formula}</span>
        </p>
      )}
      {item.points?.map((p, k) => (
        <div key={k} className="panel-2 p-3">
          <div className="mb-2 flex items-center justify-between">
            <span className="label">{fy(p.period)}</span>
            <span className="num text-[14px] text-ink-100">{p.value === null ? "unavailable" : byUnit(p.value, item.unit ?? "")}</span>
          </div>
          <InputsTable inputs={p.inputs ?? []} />
          {p.note && <p className="mt-2 text-[11px] text-warn">{p.note}</p>}
        </div>
      ))}
      {item.inputs && item.inputs.length > 0 && <InputsTable inputs={item.inputs} />}
      <p className="text-[11px] text-ink-500">
        All calculations are deterministic and run by KOI&apos;s Python analysis engine from stored source data. Nothing on
        this panel is generated by a language model.
      </p>
    </div>
  );
}

// Clickable statement: plain text in beginner mode, detail in intermediate/advanced.
export function Statement({ s, showDetail }: { s: Json; showDetail: boolean }) {
  const open = useEvidence();
  const tone = s.sentiment === "positive" ? "text-pos" : s.sentiment === "negative" ? "text-neg" : "text-ink-400";
  return (
    <button
      onClick={() =>
        open({ title: s.plain, plain: s.plain, detail: s.detail, formula: s.formula, points: s.evidence?.[0]?.period ? s.evidence : undefined,
               inputs: s.evidence?.[0]?.period ? undefined : s.evidence, unit: s.unit })
      }
      className="group flex w-full items-start gap-2.5 rounded-md px-2 py-1.5 text-left hover:bg-ink-850"
    >
      <span className={`mt-[3px] text-[11px] ${tone}`}>{s.sentiment === "negative" ? "▼" : s.sentiment === "positive" ? "▲" : "●"}</span>
      <span className="text-[13px] leading-snug">
        <span className="text-ink-100">{s.plain}</span>
        {showDetail && s.detail && <span className="mt-0.5 block text-[12px] text-ink-400">{s.detail}</span>}
        <span className="ml-1 text-[11px] text-ink-500 opacity-0 transition-opacity group-hover:opacity-100">view evidence →</span>
      </span>
    </button>
  );
}
